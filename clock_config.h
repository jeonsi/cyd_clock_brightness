// 캘리브레이션: 이 패널에서 펜으로 네 모서리를 실측한 raw ADC 범위.
// 다른 CYD 개체는 값이 다를 수 있으므로, 탭 위치가 어긋나면 TOUCH_DEBUG 1로
// 켜고 네 모서리를 눌러 나온 raw=(x,y)로 갱신:
