//   화면 오른쪽 모서리의 ry -> TOUCH_RAW_MIN_Y,  왼쪽 ry  -> TOUCH_RAW_MAX_Y
// (샘플링 방식을 바꾸면 유효 범위도 달라지므로 재측정 필요)
#define TOUCH_RAW_MIN_X 315
#define TOUCH_RAW_MAX_X 3837
#define TOUCH_RAW_MIN_Y 154
#define TOUCH_RAW_MAX_Y 3718

// 레일 검사: raw X 또는 Y가 ADC 양 끝(0 또는 4095)에서 이 값 안쪽이면 압력과 무관하게
// "접촉 없음"으로 처리. 진짜 터치는 위 캘리브레이션 범위 안에 들어오고, 0/4095는 패널이
// 떠 있을 때(특히 손을 뗀 직후 X축이 포화되는 프레임)만 나옴. 이때 압력 노이즈가 100을
// 넘으면 구석에 고스트 탭이 생기는데 이 검사가 원천 차단함. 캘리브레이션 최소값보다
// 작게 유지(50). 구석 터치가 안 잡히면 줄임(20).
#define TOUCH_RAW_RAIL 50

// 축 방향 반전. 터치가 상하 또는 좌우로 거울처럼 뒤집혀 있으면 해당 축을
// 0으로. 축 '교환'은 여기서 하지 않음 - 회전은 LVGL이 처리함.
#define TOUCH_INVERT_X 1
#define TOUCH_INVERT_Y 1

// 미세 오프셋 보정(네이티브 px). 모서리 실측 캘리브레이션이 정확하면 0.
// 270도 회전 때문에 X가 화면 '세로', Y가 화면 '가로' 축임:
//   포인터가 실제 터치보다 화면 아래를 가리키면 TOUCH_TRIM_X를 +로
//   포인터가 실제 터치보다 화면 오른쪽을 가리키면 TOUCH_TRIM_Y를 -로
#define TOUCH_TRIM_X 0
#define TOUCH_TRIM_Y 0

// 터치 패널 읽기 주기(밀리초). LVGL 기본 33ms보다 짧게 두면 빠른 스와이프도
// 샘플이 충분히 남아 이동량이 정확히 잡힘. 한 번 읽는 데 약 0.25ms라 15ms
// 주기의 부담(CPU ~2%, 전류 1mA 안팎)은 무시할 수준. 5~33 권장.
#define TOUCH_READ_PERIOD_MS 10

// 눌림 확정 지연(프레임 수). 접촉이 시작된 뒤 이 개수의 프레임(각 TOUCH_READ_PERIOD_MS)
// 은 건너뛰고 그 다음 프레임의 좌표를 "누른 지점"으로 삼음. 저항막은 누르기 시작하는
// 순간 압력이 낮아 좌표가 옆 버튼으로 튀기 쉬운데, 이걸로 오타깃이 거의 사라짐.
// 확정 전에 접촉이 끊긴 아주 짧은 스침은 터치로 치지 않음.
//   0 = 즉시 확정, 1 = 10ms 지연(기본), 2 = 더 보수적(20ms, 첫 접촉 튐을 더 걸러냄)
#define TOUCH_PRESS_CONFIRM_FRAMES 1

// 드래그 중 순간적으로 접촉이 끊겨도 이 시간(밀리초) 동안은 눌린 것으로
// 유지. 슬라이더를 끌 때는 재그리기 때문에 터치 프레임 간격이 약 50ms로 벌어지므로,
// 100이면 한 프레임 결손만 견디고 두 프레임이 빠지면 드래그가 끊김(실측 로그에서
// 80~90/100ms까지 간 결손이 반복됨). 150은 두 프레임 결손까지 흡수. 대가는 손을
// 뗀 뒤 릴리즈 전달이 그만큼 늦어지는 것. 드래그가 여전히 끊기면 200, 버튼 반응이
// 느리면 100.
#define TOUCH_RELEASE_DEBOUNCE_MS 150

// 압력(Z) 히스테리시스 - 순수한 두 값 구조. PRESS 이상이면 터치 시작, 시작 뒤에는
// RELEASE 이상이면 유지, 그 아래로 내려가야 종료. RELEASE는 시작 판정에 전혀 관여하지
// 않으므로 드래그 유지 목적으로 낮춰도 유령 터치가 생기지 않음(다만 저압 좌표는
// 부정확하므로 30~40 아래는 권장하지 않음). RELEASE는 PRESS보다 낮거나 같아야 함.
//   가만히 둬도 유령 터치가 생기면       -> TOUCH_Z_PRESS를 올림(150~300)
//   가벼운 탭/스와이프가 안 잡히면       -> TOUCH_Z_PRESS를 내림(100; 50까지 내리면 유령 터치)
//   손가락 드래그가 끊기면               -> TOUCH_Z_RELEASE를 내림(40)
// 실측: 손가락 '누름'은 1100~2250, 가벼운 플릭도 500 이상이라 시작 문턱 200은 여유가
// 있음. 반면 손가락으로 '끌' 때는 살짝 떠서 압력이 크게 떨어지므로(펜촉은 괜찮음)
// 유지 문턱 150에서는 슬라이더 드래그가 끊김 - 50이 검증된 값.
#define TOUCH_Z_PRESS      200
#define TOUCH_Z_RELEASE    50
#if TOUCH_Z_RELEASE > TOUCH_Z_PRESS
#error "TOUCH_Z_RELEASE must not exceed TOUCH_Z_PRESS (hysteresis would be inverted)"
#endif

// 노이즈 필터. 축당 TOUCH_SAMPLES번 읽어 중간 절반만 평균(이상치 제거) 후
// 프레임 간 EMA 적용. 샘플 수를 늘리면 안정적이지만 읽기 시간 증가.
// ALPHA(0~1)는 낮을수록 부드럽지만 커서가 손가락을 늦게 따라옴. 슬라이더 드래그 중에는
// 재그리기 때문에 프레임 간격이 약 50ms로 벌어져 0.4에서는 손잡이가 손가락보다 20px쯤
// 뒤따라왔음 - 0.6이면 약 10px. 정지 시 떨림·릴리즈 튐이 조금 늘어나는 대가.
#define TOUCH_SAMPLES      8
#define TOUCH_FILTER_ALPHA 0.6f

// 스와이프로 인식할 최소 이동 거리(px). 속도는 보지 않고 누른 동안의 최대
// 변위만 봄. 이 값 이상 움직이면 무조건 제스처(큰 축이 방향 결정). 모든 화면
// 공통. 화면 폭 320px 기준 80이면 화면의 1/4을 확실히 그어야 넘어가고, 버튼을
// 누르다 미끄러지는 정도로는 바뀌지 않음(실사용 기준값, 손가락 조작에 맞춰 조정됨).
//   짧은 플릭이 씹히면 60으로, 우발적 전환이 있으면 100으로.
// 빠른 플릭은 손가락이 일찍 떠서 패널이 뒷부분을 못 보므로, 속도가 탭 기준
// (TOUCH_MOVE_STEP_PX)을 넘고 이 값의 절반 이상 움직였으면 거리가 모자라도 스와이프로
// 인정함(플릭 규칙). 느리게 절반~전체 사이로 끌린 접촉은 탭도 스와이프도 아닌 것으로 무시.
#define TOUCH_SWIPE_MIN_PX 80

// 탭으로 인정할 최대 이동 거리(px). 이 값 이상(단, 스와이프 미만)으로 움직인
// 터치는 "도중에 끊긴 스와이프"로 보고 탭도 스와이프도 아닌 것으로 무시함
// (그래야 스와이프가 밝기 패널을 여는 오동작이 사라짐). 이 판정은 EMA 필터된
// 좌표의 최대 변위로 하므로 누르거나 뗄 때 한 프레임 튀는 좌표에는 영향받지 않음.
// 60이면 손가락 끝이 눌리며 미끄러지는 정도(수십 px)는 모두 탭으로 인정되고,
// 60~80px(TOUCH_SWIPE_MIN_PX 미만) 구간만 무시됨. 탭이 자꾸 무시되면 올림(70),
// 끊긴 스와이프가 탭이 되면 내림(40). 항상 TOUCH_SWIPE_MIN_PX보다 작아야 함.
#define TOUCH_TAP_MAX_PX 60
#if TOUCH_TAP_MAX_PX >= TOUCH_SWIPE_MIN_PX
#error "TOUCH_TAP_MAX_PX must be smaller than TOUCH_SWIPE_MIN_PX"
#endif

// 탭으로 인정할 최대 '프레임당' 이동(px). 손가락이 이 속도 이상으로 움직이고
// 있었다면 총 이동이 짧아도(눌림이 늦게 등록된 스와이프) 탭으로 치지 않음. 같은 값이
// 플릭 판정에도 쓰임: 이 속도 이상 + TOUCH_SWIPE_MIN_PX 절반 이상 이동 = 스와이프.
// 마지막 접촉 프레임(손이 떠나며 좌표가 튀는 구간)은 집계에서 빠지므로 lift-off
// 스파이크는 여기 걸리지 않음.
// 10ms 주기에서 6px = 초당 600px. 탭 중 손가락 떨림은 보통 1~3px/프레임.
#define TOUCH_MOVE_STEP_PX 6

// 1이면 터치 판정 과정을 시리얼에 출력(튜닝·캘리브레이션용).
//   PRESS ...    : 눌림 확정 지점과 적용 중인 문턱값(스와이프/탭 px, 속도)
//   z=.. 줄      : 매 프레임 압력·raw·네이티브·필터 좌표, 경과 시간, 최대 변위/문턱,
//                  프레임당 이동/문턱, 눌린 대상(on background / on widget)
//   confirm/dip  : 확정 지연으로 건너뛴 첫 프레임, 릴리즈 디바운스 중 압력 하락
//   RELEASE ...  : 눌린 시간, 최종 변위·속도와 각 문턱, 판정(TAP / SWIPE / IGNORED / WIDGET)
//   BLIP         : 확정 전에 끝난 접촉
// 값이 문턱에 걸리는 순간을 보고 어느 값을 움직일지 결정하면 됨.
// 네이티브 좌표는 회전 전 240x320 기준이라 화면 위치와 직접 대응하지 않음.
#define TOUCH_DEBUG 0

