// 소리를 낼 핀.
//   26 : 기본. 보드 내장 8002 앰프 -> SPEAK 커넥터(4~8옴 스피커 또는 피에조).
//        GPIO 26은 다른 곳에 노출되지 않으므로 앰프가 정상일 때만 소리가 남.
//   27 : 앰프가 불량인 보드용. 패시브 피에조 부저를 CN1 커넥터의 IO27과 GND에
