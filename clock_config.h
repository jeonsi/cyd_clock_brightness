/* =========================================================================
 * 12. 알람 시계 (여섯 번째 화면)
 *    [1][2][3]으로 편집할 알람을 고르고, H-/H+/M-/M+ 버튼으로 시각을 맞추고
 *    (길게 누르면 빠르게), 월~일 버튼으로 울릴 요일을 선택(최소 1개), "1x"를
 *    켜면 요일이 "다음에 울릴 날" 하나로 좁혀지고(알람 시각이 아직 안 지났으면
 *    오늘, 지났으면 내일; 시각을 바꾸면 따라 갱신) 한 번 울린 뒤 스스로 OFF,
 *    1x를 끄면 이전 요일 선택이 복원됨. 요일을 직접 바꾸면 1x는 꺼짐.
 *    🔔 버튼으로 ON/OFF. 선택 버튼의
 *    🔔 표시는 그 알람이 ON이라는 뜻. 시계 화면 우하단에는 알람마다 종 아이콘이
 *    하나씩 있고 OFF면 사선이 그어짐. 이 화면에서는 바탕 탭이 무시됨(스와이프는
 *    다른 화면과 동일). ✓ OK 버튼은 설정을 NVS에 저장하고 다음 화면으로 넘어감.
 * ========================================================================= */

// 알람 개수. 선택 버튼 폭(56px, 간격 64px) 기준으로 4개까지는 한 줄에 들어감.
#define ALARM_COUNT      3

// 알람 하나의 상태. (여기에 두는 이유: Arduino IDE가 함수 프로토타입을 스케치
// 상단에 자동 삽입하므로, 함수 인자로 쓰이는 타입은 헤더에서 먼저 정의돼야 함)
typedef struct {
  int     hh, mm;      // 알람 시각(24시간 기준)
  bool    enabled;     // ON/OFF
  uint8_t days;        // 울릴 요일 비트마스크, 비트 0 = 일요일(tm_wday)
  bool    once;        // 1x: 한 번 울린 뒤 스스로 OFF
  uint8_t days_saved;  // 1x를 끌 때 복원할 요일(저장 안 됨)
} alarm_t;

// 저장값이 없을 때(첫 부팅)의 알람 시각. 24시간 기준. 모든 알람에 적용.
#define ALARM_DEFAULT_HH 7
