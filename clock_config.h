#define BL_PANEL_TIMEOUT_MS 4000

// 화면 자동 꺼짐 시간. 마지막 터치 뒤 이 시간(밀리초)이 지나면 백라이트를 완전히 끄고,
// 다시 터치하면 켜짐. 화면을 깨운 그 터치는 버튼·스와이프로 전달되지 않음(깨우다가
// 버튼이 눌리는 일 방지). 타이머·알람이 울리면 자동으로 켜지고 울리는 동안은 꺼지지
// 않음. 부팅(Wi-Fi/시간 동기화) 중에도 꺼지지 않음.
// 자동 꺼짐/항상 켜기는 밝기 패널의 전원 버튼(12H/24H 옆)으로 선택하며 NVS에 저장됨 -
// 버튼은 자동 꺼짐일 때 이 시간("30s"/"5m")을, 항상 켜기일 때 "ON"을 표시.
// 0이면 기능과 버튼을 모두 빼고 항상 켜짐.
